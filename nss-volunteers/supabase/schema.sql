create extension if not exists pgcrypto;

-- ------------------------------------------------------------
-- PROFILES
-- One profile row per authenticated user.
-- ------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  class text not null default '',
  roll_no text not null default '',
  phone text not null default '',
  email text not null default '',
  father_name text not null default '',
  mother_name text not null default '',
  photo_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_roll_no_format
    check (roll_no = '' or roll_no ~ '^UA-[A-Za-z0-9]+-[A-Za-z0-9]+$')
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
before update on public.profiles
for each row execute procedure public.set_updated_at();

alter table public.profiles enable row level security;

drop policy if exists "Users can view own profile" on public.profiles;
create policy "Users can view own profile"
on public.profiles for select to authenticated
using (auth.uid() = id);

drop policy if exists "Users can insert own profile" on public.profiles;
create policy "Users can insert own profile"
on public.profiles for insert to authenticated
with check (auth.uid() = id);

drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile"
on public.profiles for update to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

-- ------------------------------------------------------------
-- CERTIFICATES
-- A certificate generated by a user.
-- ------------------------------------------------------------
create table if not exists public.certificates (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  certificate_key text not null,
  certificate_title text not null,
  generated_at timestamptz not null default now(),
  unique(user_id, certificate_key)
);

alter table public.certificates enable row level security;

drop policy if exists "Users can view own certificates" on public.certificates;
create policy "Users can view own certificates"
on public.certificates for select to authenticated
using (auth.uid() = user_id);

-- Inserts are deliberately restricted to the RPC below.
-- Users cannot directly insert certificates from the browser.

-- ------------------------------------------------------------
-- CERTIFICATE ATTEMPTS
-- Stores the failed-code lockout until timestamp.
-- ------------------------------------------------------------
create table if not exists public.certificate_attempts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  certificate_key text not null,
  locked_until timestamptz,
  last_failed_at timestamptz not null default now(),
  unique(user_id, certificate_key)
);

alter table public.certificate_attempts enable row level security;

drop policy if exists "Users can view own certificate attempts" on public.certificate_attempts;
create policy "Users can view own certificate attempts"
on public.certificate_attempts for select to authenticated
using (auth.uid() = user_id);

