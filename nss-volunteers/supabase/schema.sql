-- ------------------------------------------------------------
-- SECURE CERTIFICATE RPC
--
-- IMPORTANT: Certificate codes are intentionally NOT stored in
-- a public table. They are checked inside this server-side
-- SECURITY DEFINER function.
--
-- Change the three codes below before real deployment if needed.
-- ------------------------------------------------------------
create or replace function public.generate_certificate(
  p_certificate_key text,
  p_code text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_expected text;
  v_title text;
  v_locked_until timestamptz;
  v_existing public.certificates;
begin
  if v_user is null then
    raise exception 'Not authenticated';
  end if;

  if p_certificate_key not in ('certificate-1','certificate-2','certificate-3') then
    raise exception 'Invalid certificate';
  end if;

  -- ==========================================================
  -- FUTURE CERTIFICATE CONFIG:
  -- Add/change certificate keys, titles and codes here.
  -- Keep the codes server-side; do NOT put secret codes in
  -- React source code.
  -- ==========================================================
  case p_certificate_key
    when 'certificate-1' then
      v_expected := '99';
      v_title := 'NSS Certificate 1';
    when 'certificate-2' then
      v_expected := '78';
      v_title := 'NSS Certificate 2';
    when 'certificate-3' then
      v_expected := '23';
      v_title := 'NSS Certificate 3';
  end case;

  select *
  into v_existing
  from public.certificates
  where user_id = v_user
    and certificate_key = p_certificate_key
  limit 1;

  if found then
    return jsonb_build_object(
      'status','already_generated',
      'certificate_id',v_existing.id,
      'generated_at',v_existing.generated_at
    );
  end if;

  select locked_until
  into v_locked_until
  from public.certificate_attempts
  where user_id = v_user
    and certificate_key = p_certificate_key;

  if v_locked_until is not null and v_locked_until > now() then
    return jsonb_build_object(
      'status','locked',
      'locked_until',v_locked_until
    );
  end if;

  if p_code is distinct from v_expected then
    insert into public.certificate_attempts(
      user_id, certificate_key, locked_until, last_failed_at
    )
    values (
      v_user, p_certificate_key, now() + interval '24 hours', now()
    )
    on conflict (user_id, certificate_key)
    do update set
      locked_until = now() + interval '24 hours',
      last_failed_at = now();

    return jsonb_build_object(
      'status','wrong_code',
      'locked_until',now() + interval '24 hours'
    );
  end if;

  insert into public.certificates(
    user_id, certificate_key, certificate_title
  )
  values (
    v_user, p_certificate_key, v_title
  )
  on conflict (user_id, certificate_key) do nothing
  returning * into v_existing;

  return jsonb_build_object(
    'status','generated',
    'certificate_id',v_existing.id,
    'certificate_key',p_certificate_key,
    'certificate_title',v_title,
    'generated_at',v_existing.generated_at
  );
end;
$$;

revoke all on function public.generate_certificate(text,text) from public;
grant execute on function public.generate_certificate(text,text) to authenticated;

-- ------------------------------------------------------------
-- OPTIONAL: Create profile row automatically on signup.
-- The website still requires the details form to be completed.
-- ------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, coalesce(new.email, ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();
